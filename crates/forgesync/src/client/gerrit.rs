//! Transport Gerrit : REST `/changes/` — lecture anonyme (instances
//! publiques), écriture via `token_env` (`user:pass` → Basic, sinon
//! Bearer). Pas de `gh`-like CLI : git+ssh pour fetch les patchsets
//! reste côté démon (worktree), hors périmètre de ce client.

use super::{
    norm_ts, token_value, ChangeComment, ChangeInfo, ForgeCaps, ForgeClient, ForgeSpec,
    ForgeTarget, ListQuery,
};
use crate::{gerrit_state, host_base, http_get, http_send, urlenc, Http};
use serde_json::{json, Value};

/// Change JSON → ChangeInfo — `current_revision`/`revisions` donnent
/// le SHA du patchset courant quand demandés (`o=CURRENT_REVISION`).
fn gerrit_change(v: &Value) -> ChangeInfo {
    let head_sha = v["current_revision"]
        .as_str()
        .map(str::to_string)
        .or_else(|| {
            v["revisions"]
                .as_object()
                .and_then(|m| m.keys().next().cloned())
        })
        .unwrap_or_default();
    // Owner — même convention que les commentaires (`gerrit_msg`) :
    // compte enregistré → MEMBER. Pas de notion de fork sur Gerrit :
    // un change vit toujours dans son projet → `cross_repo` = false.
    let owner_id = v["owner"]["_account_id"]
        .as_u64()
        .map(|i| i.to_string())
        .unwrap_or_default();
    ChangeInfo {
        number: v["_number"].as_u64().unwrap_or(0),
        change_id: v["change_id"].as_str().map(String::from),
        title: v["subject"].as_str().unwrap_or("").into(),
        state: gerrit_state(v),
        // `branch` Gerrit = branche de DESTINATION (il n'y a pas de
        // branche source : le patchset se fetch via refs/changes/*) —
        // mappée sur `base` pour que le filtre `integration_branch`
        // de la review s'applique ; `branch` reste vide.
        base: v["branch"].as_str().unwrap_or("").into(),
        head_sha,
        resolved_repo: v["project"].as_str().map(String::from),
        author: v["owner"]["username"]
            .as_str()
            .or_else(|| v["owner"]["name"].as_str())
            .unwrap_or("")
            .into(),
        author_id: owner_id.clone(),
        author_assoc: if owner_id.is_empty() {
            "NONE".into()
        } else {
            "MEMBER".into()
        },
        cross_repo: Some(false),
        ..Default::default()
    }
}

/// Message Gerrit (`o=MESSAGES`) → commentaire — les messages sans
/// `author` sont des events système (bots taggés comptent aussi). `id`
/// = index chronologique (les messages n'ont pas d'identifiant forge :
/// append-only, l'ordre est stable pour `id > last_trigger`).
fn gerrit_msg(idx: usize, v: &Value) -> ChangeComment {
    let account = v["author"]["_account_id"]
        .as_u64()
        .map(|i| i.to_string())
        .unwrap_or_default();
    ChangeComment {
        id: idx as u64 + 1,
        author: v["author"]["username"]
            .as_str()
            .or_else(|| v["author"]["name"].as_str())
            .unwrap_or("")
            .into(),
        author_id: account.clone(),
        // Compte enregistré → membre ; anonyme/bot → sans droit.
        assoc: if account.is_empty() {
            "NONE".into()
        } else {
            "MEMBER".into()
        },
        body: v["message"].as_str().unwrap_or("").into(),
        created_at: norm_ts(v["date"].as_str().unwrap_or("")),
        system: v["author"]["username"].as_str().is_none()
            || v["tag"]
                .as_str()
                .is_some_and(|t| t.starts_with("autogenerated")),
    }
}

/// REST Gerrit — headers : `token_env` → `Basic base64(user:pass)` si
/// la valeur contient `:` (mot de passe HTTP Gerrit), sinon `Bearer`.
pub struct GerritRestClient {
    target: ForgeTarget,
    base: String,
    token: Option<String>,
}

impl GerritRestClient {
    pub fn new(spec: ForgeSpec, target: ForgeTarget) -> Self {
        Self {
            base: host_base(&spec.host),
            target,
            token: token_value(spec.token_env.as_deref()),
        }
    }

    fn headers(&self) -> Vec<(&'static str, String)> {
        match &self.token {
            Some(t) if t.contains(':') => {
                vec![("Authorization", format!("Basic {}", b64_encode(t)))]
            }
            Some(t) => vec![("Authorization", format!("Bearer {t}"))],
            None => Vec::new(),
        }
    }

    fn get(&self, path: &str) -> Http {
        http_get(&format!("{}{path}", self.base), &self.headers())
    }
}

/// base64 (RFC 4648) — les workers n'ont pas besoin d'une crate pour
/// encoder `user:password` Gerrit.
fn b64_encode(s: &str) -> String {
    const A: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(s.len().div_ceil(3) * 4);
    for chunk in s.as_bytes().chunks(3) {
        let b = [
            chunk[0],
            *chunk.get(1).unwrap_or(&0),
            *chunk.get(2).unwrap_or(&0),
        ];
        out.push(A[(b[0] >> 2) as usize] as char);
        out.push(A[(((b[0] & 3) << 4) | (b[1] >> 4)) as usize] as char);
        out.push(if chunk.len() > 1 {
            A[(((b[1] & 15) << 2) | (b[2] >> 6)) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            A[(b[2] & 63) as usize] as char
        } else {
            '='
        });
    }
    out
}

impl ForgeClient for GerritRestClient {
    fn caps(&self) -> ForgeCaps {
        ForgeCaps {
            list: true,
            comments: true,
            post: self.token.is_some(),
            mark_ready: self.token.is_some(),
            checks: false,
            rollup: true,
        }
    }

    fn list_changes(&self, q: &ListQuery) -> Option<Vec<ChangeInfo>> {
        let status = match q.state.as_deref() {
            Some("open") => "+status:open",
            Some("draft") => "+status:open+is:wip",
            _ => "",
        };
        match self.get(&format!(
            "/changes/?q=project:{}{status}&o=CURRENT_REVISION&o=CURRENT_COMMIT&n={}",
            urlenc(&self.target.repo),
            q.limit.min(200)
        )) {
            Http::Ok(v) => v.as_array().map(|a| a.iter().map(gerrit_change).collect()),
            _ => None,
        }
    }

    fn get_change(&self, id: &str) -> Option<ChangeInfo> {
        // `/changes/<id>` accepte numéro et Change-Id.
        match self.get(&format!(
            "/changes/{id}?o=CURRENT_REVISION&o=CURRENT_COMMIT"
        )) {
            Http::Ok(v) => Some(gerrit_change(&v)),
            _ => None,
        }
    }

    fn list_comments(&self, id: &str, since: Option<&str>) -> Option<Vec<ChangeComment>> {
        match self.get(&format!("/changes/{id}?o=MESSAGES")) {
            Http::Ok(v) => v["messages"].as_array().map(|a| {
                a.iter()
                    .enumerate()
                    .map(|(i, m)| gerrit_msg(i, m))
                    .filter(|c| since.is_none_or(|s| c.created_at.as_str() >= s))
                    .collect()
            }),
            _ => None,
        }
    }

    /// « Commentaire » Gerrit = review message sur le patchset courant
    /// (le verdict de review s'y affiche comme sur une note MR).
    fn post_comment(&self, id: &str, body: &str) -> bool {
        if self.token.is_none() {
            return false;
        }
        matches!(
            http_send(
                "POST",
                &format!("{}/changes/{id}/revisions/current/review", self.base),
                &self.headers(),
                &json!({"message": body}),
            ),
            Http::Ok(_)
        )
    }

    fn mark_ready(&self, id: &str) -> bool {
        if self.token.is_none() {
            return false;
        }
        matches!(
            http_send(
                "POST",
                &format!("{}/changes/{id}:ready", self.base),
                &self.headers(),
                &json!({}),
            ),
            Http::Ok(_)
        )
    }

    fn mark_draft(&self, id: &str) -> bool {
        if self.token.is_none() {
            return false;
        }
        matches!(
            http_send(
                "POST",
                &format!("{}/changes/{id}:wip", self.base),
                &self.headers(),
                &json!({}),
            ),
            Http::Ok(_)
        )
    }

    /// `refs/changes/<NN>/<num>/<ps>` du patchset courant — le numéro
    /// de patchset est dans `revisions[sha]._number` du change.
    fn head_ref(&self, id: &str) -> Option<String> {
        let c = self.get_change(id)?;
        let n = c.number;
        let ps = match self.get(&format!("/changes/{id}?o=CURRENT_REVISION")) {
            Http::Ok(v) => {
                let sha = v["current_revision"].as_str()?;
                v["revisions"][sha]["_number"].as_u64()
            }
            _ => None,
        }?;
        Some(format!("refs/changes/{:02}/{n}/{ps}", n % 100))
    }

    fn verify(&self, id: &str) -> Option<bool> {
        match self.get(&format!("/changes/{id}")) {
            Http::Ok(_) => Some(true),
            Http::Code(401) | Http::Code(403) | Http::Code(404) => Some(false),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `branch` Gerrit = destination → `base` (filtre
    /// `integration_branch` de la review), `branch` vide — sans ça
    /// aucun change ne passerait le filtre de base.
    #[test]
    fn gerrit_change_mappe_la_destination_sur_base() {
        let c = gerrit_change(&json!({
            "_number": 4242,
            "change_id": "Ideadbeef",
            "subject": "titre",
            "status": "NEW",
            "branch": "next_release",
            "project": "plat/app",
            "current_revision": "abc123"
        }));
        assert_eq!(c.base, "next_release");
        assert!(c.branch.is_empty());
        assert_eq!(c.head_sha, "abc123");
        assert_eq!(c.resolved_repo.as_deref(), Some("plat/app"));
    }

    #[test]
    fn b64_rfc4648() {
        assert_eq!(b64_encode(""), "");
        assert_eq!(b64_encode("f"), "Zg==");
        assert_eq!(b64_encode("fo"), "Zm8=");
        assert_eq!(b64_encode("foo"), "Zm9v");
        assert_eq!(b64_encode("user:pass"), "dXNlcjpwYXNz");
    }
}
