import puppeteer from "puppeteer-core";
import { spawn } from "node:child_process";
import { readFileSync } from "node:fs";
const server = spawn("npx", ["vite", "preview", "--port", "4173", "--strictPort"], { cwd: process.cwd(), stdio: "ignore" });
await new Promise(r => setTimeout(r, 1800));
const b = await puppeteer.launch({ executablePath: "/usr/bin/chromium", headless: "new", args: ["--no-sandbox"] });
const p = await b.newPage();
await p.setViewport({ width: 412, height: 915, deviceScaleFactor: 2.625, isMobile: true, hasTouch: true });
await p.setUserAgent("Mozilla/5.0 (Linux; Android 15; SM-S931B) AppleWebKit/537.36 Chrome/131 Mobile");
await p.evaluateOnNewDocument(readFileSync("tests/tauri-mock.js", "utf8"));
const shot = async (n, ms = 400) => { await new Promise(r => setTimeout(r, ms)); await p.screenshot({ path: `shots/${n}.png` }); console.log("->", n); };
const lp = async (sel) => { const e = await p.$(sel); const x = await e.boundingBox(); const c = await p.createCDPSession(); await c.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: x.x + x.width / 2, y: x.y + 25, id: 1 }] }); await new Promise(r => setTimeout(r, 650)); await c.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] }); };
await p.goto("http://localhost:4173/", { waitUntil: "networkidle0" });
await p.tap("#tb-more"); await shot("20-more-sheet");
await p.evaluate(() => [...document.querySelectorAll("#omenu .om-item")].find(x => /settings|param/i.test(x.textContent))?.click());
await shot("21-settings", 500);
await p.keyboard.press("Escape"); await new Promise(r => setTimeout(r, 200));
await p.tap("#tb-more"); await new Promise(r => setTimeout(r, 300));
await p.evaluate(() => [...document.querySelectorAll("#omenu .om-item")].find(x => /about|propos/i.test(x.textContent))?.click());
await shot("22-about", 500);
await p.keyboard.press("Escape"); await new Promise(r => setTimeout(r, 200));
await p.tap("#tb-menu"); await new Promise(r => setTimeout(r, 350));
await p.tap("#btn-connect"); await new Promise(r => setTimeout(r, 400));
await p.type("#c-host", "me@pi5.local"); await p.tap("#c-go"); await new Promise(r => setTimeout(r, 900));
await lp(".sess"); await shot("23-group-sheet", 500);
await b.close(); server.kill(); console.log("done");
